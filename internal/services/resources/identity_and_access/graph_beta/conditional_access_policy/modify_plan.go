package graphBetaConditionalAccessPolicy

import (
	"context"
	"fmt"

	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-log/tflog"
)

// ModifyPlan handles plan modification for conditional access policies. No plan changes are needed.
func (r *ConditionalAccessPolicyResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}

	tflog.Debug(ctx, fmt.Sprintf("ModifyPlan: no plan modifications needed for %s", ResourceName))
}
