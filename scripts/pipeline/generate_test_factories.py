#!/usr/bin/env python3
"""Generate isolated test registries from production constructors and package fixtures."""

import argparse
import re
import subprocess
from pathlib import Path

MODULE = 'github.com/deploymenttheory/terraform-provider-microsoft365'
REGISTRIES = {
    'resources.go': ('Resources', 'resource', 'Resource'),
    'datasources.go': ('DataSources', 'datasource', 'DataSource'),
    'actions.go': ('Actions', 'action', 'Action'),
    'list_resources.go': ('ListResources', 'list', 'ListResource'),
    'ephemeral_resources.go': ('EphemeralResources', 'ephemeral', 'EphemeralResource'),
}
HEADER = '// Code generated by scripts/pipeline/generate_test_factories.py. DO NOT EDIT.\n'
FILENAME = 'provider_factories_test.go'


def without_comments(source):
    """Remove Go comments without interpreting comment markers inside strings."""
    return re.sub(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|`[^`]*`',
                  lambda m: m.group() if m.group()[0] in ('"', '`') else '', source)


def inventory(root):
    """Read the production registrations without importing or compiling the provider."""
    entries = []
    for filename, (field, framework, interface) in REGISTRIES.items():
        source = without_comments((root / 'internal/provider' / filename).read_text(encoding='utf-8'))
        imports = dict(re.findall(r'(\w+)\s+"(' + re.escape(MODULE) + r'/internal/services/[^"\n]+)"', source))
        for alias, constructor in re.findall(r'^\s*(\w+)\.(New\w+)\s*,', source, re.M):
            path = imports[alias]
            directory = root / path.removeprefix(MODULE + '/')
            declarations = '\n'.join(without_comments(p.read_text(encoding='utf-8')) for p in directory.glob('*.go') if not p.name.endswith('_test.go'))
            names = set(re.findall(r'\b(?:ResourceName|DataSourceName|ActionName|ListResourceName|EphemeralResourceName)\s*=\s*"([^"]+)"', declarations))
            if not names:
                names = set(re.findall(r'resp.TypeName\s*=\s*req.ProviderTypeName\s*\+\s*"([^"]+)"', declarations))
            if len(names) != 1:
                raise ValueError(f'Expected one Terraform type name for {path}: {sorted(names)}')
            name = names.pop()
            if not name.startswith('microsoft365_'):
                name = 'microsoft365_' + name.lstrip('_')
            entries.append((field, framework, interface, path, constructor, name))
    if not entries:
        raise ValueError('No production constructors discovered')
    return entries


def selected_entries(root, directory, entries):
    """Include the package under test and every registered type referenced by its fixtures."""
    sources = []
    for path in (root / directory).rglob('*'):
        if path.is_file() and path.suffix in ('.tf', '.go') and path.name != FILENAME:
            sources.append(path.read_text(encoding='utf-8'))
    source = '\n'.join(sources)
    block_fields = {'resource': 'Resources', 'data': 'DataSources', 'action': 'Actions',
                    'list': 'ListResources', 'ephemeral': 'EphemeralResources'}
    references = {(block_fields[kind], name) for kind, name in re.findall(
        r'\b(resource|data|action|list|ephemeral)\s+"(microsoft365_[a-zA-Z0-9_]+)"', source.replace('\\"', '"'))}
    imports = set(re.findall(r'"(' + re.escape(MODULE) + r'/internal/services/[^"\n]+)"', source))
    own_path = MODULE + '/' + directory.as_posix()
    return [entry for entry in entries if entry[3] == own_path or entry[3] in imports or (entry[0], entry[5]) in references]


def render(package_name, entries):
    """Render local unit and acceptance factories with explicit constructor imports."""
    lines = [HEADER, f'package {package_name}\n\nimport (\n',
             f'"{MODULE}/internal/mocks"\n',
             f'providercore "{MODULE}/internal/provider/core"\n']
    for framework in sorted({entry[1] for entry in entries}):
        lines.append(f'"github.com/hashicorp/terraform-plugin-framework/{framework}"\n')
    aliases = {path: f'testProvider{index}' for index, path in enumerate(sorted({entry[3] for entry in entries}))}
    for path, alias in aliases.items():
        lines.append(f'{alias} "{path}"\n')
    lines.append(')\n\nvar testProviderRegistry = providercore.Registry{\n')
    for field, framework, interface in REGISTRIES.values():
        selected = [entry for entry in entries if entry[0] == field]
        if selected:
            lines.append(f'{field}: []func() {framework}.{interface}{{\n')
            lines.extend(f'{aliases[entry[3]]}.{entry[4]},\n' for entry in selected)
            lines.append('},\n')
    lines.append('}\n\n')
    lines.append('var testUnitTestProtoV6ProviderFactories = mocks.NewProviderFactories(true, testProviderRegistry)\n')
    lines.append('var testAccProtoV6ProviderFactories = mocks.NewProviderFactories(false, testProviderRegistry)\n')
    return subprocess.run(['gofmt'], input=''.join(lines), text=True, capture_output=True, check=True).stdout


def generate(root, check=False):
    """Generate deterministic factories, or fail when checked-in factories are stale."""
    entries = inventory(root)
    directories = set()
    for path in (root / 'internal').rglob('*_test.go'):
        source = path.read_text(encoding='utf-8')
        if any(name in source for name in ('testUnitTestProtoV6ProviderFactories', 'testAccProtoV6ProviderFactories',
                                           'mocks.TestUnitTestProtoV6ProviderFactories', 'mocks.TestAccProtoV6ProviderFactories')):
            directories.add(path.parent.relative_to(root))
    stale = []
    for directory in sorted(directories):
        files = list((root / directory).glob('*_test.go'))
        consumers = [p for p in files if p.name != FILENAME and re.search(r'(?:test(?:UnitTest|Acc)|mocks.Test(?:UnitTest|Acc))ProtoV6ProviderFactories', p.read_text(encoding='utf-8'))]
        if not consumers:
            target = root / directory / FILENAME
            if target.exists() and target.read_text(encoding='utf-8').startswith(HEADER):
                stale.append(str(target))
                if not check:
                    target.unlink()
            continue
        packages = {re.search(r'^package\s+(\w+)', p.read_text(encoding='utf-8'), re.M).group(1) for p in consumers}
        if len(packages) != 1:
            raise ValueError(f'Multiple test packages consume factories in {directory}: {packages}')
        generated = render(packages.pop(), selected_entries(root, directory, entries))
        target = root / directory / FILENAME
        if target.exists() and not target.read_text(encoding='utf-8').startswith(HEADER):
            raise ValueError(f'Refusing to overwrite a manually maintained factory: {target}')
        if not target.exists() or target.read_text(encoding='utf-8') != generated:
            stale.append(str(target))
            if not check:
                target.write_text(generated, encoding='utf-8')
        for path in consumers:
            original = path.read_text(encoding='utf-8')
            updated = original.replace('mocks.TestUnitTestProtoV6ProviderFactories', 'testUnitTestProtoV6ProviderFactories').replace('mocks.TestAccProtoV6ProviderFactories', 'testAccProtoV6ProviderFactories')
            if not re.search(r'\bmocks\.', without_comments(updated)):
                updated = re.sub(r'^\s*"' + re.escape(MODULE) + r'/internal/mocks"\s*\n', '', updated, flags=re.M)
            if updated != original:
                stale.append(str(path))
                if not check:
                    path.write_text(updated, encoding='utf-8')
    print(f'{len(entries)} production constructors; {len(directories)} isolated test packages')
    if check and stale:
        raise ValueError('Stale isolated factories; run python scripts/pipeline/generate_test_factories.py:\n' + '\n'.join(stale))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generate(Path('.'), args.check)
